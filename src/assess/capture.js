import { APP_NAME, EDITION, VERSION } from '../config.js';
import { timestampForFile } from '../util/math.js';

function niceScale(mpp, maxPx) {
  const maxM = mpp * maxPx;
  const steps = [1, 2, 5, 10, 20, 25, 50, 100, 200, 500];
  let m = steps[0];
  for (const s of steps) if (s <= maxM) m = s;
  return { metres: m, px: m / mpp };
}

function sanitise(s) {
  return String(s || '').replace(/[^A-Za-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '') || 'UIN';
}

// Composes an assessment capture from the current WebGL frame. Must be called in the same
// task as renderer.render() so the drawing buffer is still valid.
export function composeCapture(glCanvas, meta) {
  const scale = Math.max(1, Math.min(2, glCanvas.width / 1400));
  const W = glCanvas.width;
  const headerH = Math.round(96 * scale);
  const footerH = Math.round((meta.stats?.length ? 92 : 46) * scale);
  const H = glCanvas.height + headerH + footerH;
  const c = document.createElement('canvas');
  c.width = W;
  c.height = H;
  const ctx = c.getContext('2d');
  const now = meta.date || new Date();

  ctx.fillStyle = '#0b1220';
  ctx.fillRect(0, 0, W, H);
  ctx.drawImage(glCanvas, 0, headerH);

  const px = (n) => Math.round(n * scale);
  const pad = px(18);

  // Header
  ctx.fillStyle = '#22d3ee';
  ctx.fillRect(0, headerH - px(3), W, px(3));
  ctx.fillStyle = '#e6edf6';
  ctx.font = `700 ${px(24)}px system-ui, -apple-system, Segoe UI, sans-serif`;
  ctx.textBaseline = 'top';
  ctx.fillText(meta.title || 'Flight Path Assessment', pad, px(14));
  ctx.font = `600 ${px(14)}px system-ui, -apple-system, Segoe UI, sans-serif`;
  ctx.fillStyle = '#94a3b8';
  ctx.fillText(`${APP_NAME} v${VERSION} - ${EDITION === 'demo' ? 'Demo' : 'Base'} Edition - ${meta.view || ''}`, pad, px(46));
  ctx.fillText(now.toLocaleString(), pad, px(68));

  const right = [
    ['Registration (UIN)', meta.registration || '-'],
    ['Pilot / Trainee', meta.pilot || '-'],
    ['Instructor', meta.instructor || '-'],
    ['Organisation', meta.organisation || '-'],
  ];
  ctx.textAlign = 'right';
  right.forEach(([k, v], i) => {
    const y = px(12 + i * 20);
    ctx.fillStyle = '#94a3b8';
    ctx.font = `500 ${px(13)}px system-ui, sans-serif`;
    ctx.fillText(`${k}:`, W - pad - px(190), y);
    ctx.fillStyle = '#ffffff';
    ctx.font = `700 ${px(14)}px ui-monospace, Menlo, Consolas, monospace`;
    ctx.fillText(String(v).slice(0, 26), W - pad, y);
  });
  ctx.textAlign = 'left';

  // Scale bar + north arrow for the overhead view.
  const y0 = headerH;
  if (meta.mppDevice) {
    const bar = niceScale(meta.mppDevice, px(240));
    const bx = pad;
    const by = y0 + glCanvas.height - px(36);
    ctx.fillStyle = 'rgba(11,18,32,0.75)';
    ctx.fillRect(bx - px(8), by - px(24), bar.px + px(80), px(44));
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(bx, by, bar.px, px(6));
    ctx.fillStyle = '#0b1220';
    ctx.fillRect(bx + bar.px / 2, by, bar.px / 2, px(6));
    ctx.strokeStyle = '#ffffff';
    ctx.lineWidth = px(1.5);
    ctx.strokeRect(bx, by, bar.px, px(6));
    ctx.fillStyle = '#ffffff';
    ctx.font = `700 ${px(13)}px system-ui, sans-serif`;
    ctx.fillText(`${bar.metres} m`, bx + bar.px + px(8), by - px(4));
    ctx.fillText('0', bx - px(2), by - px(18));
    // North arrow (north is up in the overhead view).
    const nx = W - pad - px(24);
    const ny = y0 + px(28);
    ctx.fillStyle = 'rgba(11,18,32,0.75)';
    ctx.beginPath();
    ctx.arc(nx, ny + px(8), px(24), 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = '#f43f5e';
    ctx.beginPath();
    ctx.moveTo(nx, ny - px(10));
    ctx.lineTo(nx - px(8), ny + px(12));
    ctx.lineTo(nx + px(8), ny + px(12));
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = '#ffffff';
    ctx.font = `800 ${px(12)}px system-ui, sans-serif`;
    ctx.textAlign = 'center';
    ctx.fillText('N', nx, ny + px(14));
    ctx.textAlign = 'left';
  }

  // Footer stats
  const fy = headerH + glCanvas.height;
  ctx.fillStyle = '#22d3ee';
  ctx.fillRect(0, fy, W, px(2));
  ctx.textBaseline = 'top';
  const stats = meta.stats || [];
  const colW = Math.max(px(150), (W - 2 * pad) / Math.max(Math.min(stats.length, 8), 1));
  stats.slice(0, 16).forEach(([k, v], i) => {
    const row = Math.floor(i / 8);
    const col = i % 8;
    const x = pad + col * colW;
    const y = fy + px(10 + row * 40);
    ctx.fillStyle = '#94a3b8';
    ctx.font = `500 ${px(11)}px system-ui, sans-serif`;
    ctx.fillText(k.toUpperCase(), x, y);
    ctx.fillStyle = '#ffffff';
    ctx.font = `700 ${px(15)}px ui-monospace, Menlo, Consolas, monospace`;
    ctx.fillText(String(v), x, y + px(14));
  });
  ctx.fillStyle = '#64748b';
  ctx.font = `500 ${px(11)}px system-ui, sans-serif`;
  ctx.textAlign = 'right';
  ctx.fillText(`Generated by ${APP_NAME} training simulator - not a flight record of a real aircraft`, W - pad, H - px(18));
  ctx.textAlign = 'left';

  const filename = `${APP_NAME}_${sanitise(meta.registration)}_${meta.kind || 'trail'}_${timestampForFile(now)}.png`;
  return { canvas: c, filename };
}

export function downloadCanvas(canvas, filename) {
  return new Promise((resolve) => {
    canvas.toBlob((blob) => {
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      a.remove();
      resolve({ url, blob });
    }, 'image/png');
  });
}

export function downloadText(text, filename, type = 'text/csv') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
